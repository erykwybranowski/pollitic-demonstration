import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const sitemapFile = resolve(frontendRoot, 'public/sitemap.xml');

// These three source modules contain only constants and pure functions, with
// no imports. Transpile them in memory to reuse the actual application config
// and path builder on Node 18, without copying lists or parsing TS with regexes.
export async function loadConfigModule(relativePath) {
  const source = await readFile(resolve(frontendRoot, relativePath), 'utf8');
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
  });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
}

const [languageConfig, countryConfig, siteConfig] = await Promise.all([
  loadConfigModule('src/app/i18n/language-config.ts'),
  loadConfigModule('src/app/routing/country-routes.ts'),
  loadConfigModule('src/app/seo/site-config.ts'),
]);

export const languages = [...languageConfig.SUPPORTED_LANGUAGE_CODES];
export const countries = [...countryConfig.SUPPORTED_COUNTRY_CODES];
export const defaultLanguage = languageConfig.DEFAULT_LANGUAGE_CODE;
export const siteUrl = siteConfig.SITE_URL;
export const contentPaths = [
  ...siteConfig.STATIC_INDEXABLE_PATHS.map(path => path ? [path] : []),
  ...countries.map(country => ['country', country]),
  ...countries.map(country => ['compare', country]),
];

export function localizedUrl(language, segments) {
  return new URL(languageConfig.buildLocalizedPath(language, segments), siteUrl).href;
}

export function neutralUrl(segments) {
  return new URL(`/${segments.join('/')}`, siteUrl).href;
}

export function escapeXml(value) {
  return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&apos;');
}

export function generateSitemap() {
  if (new Set(languages).size !== languages.length || !languages.includes(defaultLanguage)) {
    throw new Error('Language configuration contains duplicates or lacks the default language.');
  }
  if (new Set(countries).size !== countries.length) {
    throw new Error('Country configuration contains duplicates.');
  }
  const lines = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- Generated by npm run generate:sitemap. Do not edit manually. -->',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">',
  ];
  for (const segments of contentPaths) {
    const alternates = [
      ...languages.map(language => ({ language, url: localizedUrl(language, segments) })),
      { language: 'x-default', url: neutralUrl(segments) },
    ].map(({ language, url }) =>
      `    <xhtml:link rel="alternate" hreflang="${escapeXml(language)}" href="${escapeXml(url)}" />`);
    for (const language of languages) {
      lines.push('  <url>', `    <loc>${escapeXml(localizedUrl(language, segments))}</loc>`,
        ...alternates, '  </url>');
    }
  }
  lines.push('</urlset>', '');
  const xml = lines.join('\n');
  if (languages.length * contentPaths.length > 50_000 || Buffer.byteLength(xml) > 50 * 1024 * 1024) {
    throw new Error('Sitemap exceeds the single-file limit; split it before adding more pages.');
  }
  return xml;
}

async function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) {
    throw new Error('Usage: node scripts/generate-sitemap.mjs [--check]');
  }
  // Do not advertise languages whose catalog is missing or invalid.
  for (const language of languages) {
    JSON.parse(await readFile(resolve(frontendRoot, `public/i18n/${language}.json`), 'utf8'));
  }
  const xml = generateSitemap();
  if (process.argv.includes('--check')) {
    const existing = await readFile(sitemapFile, 'utf8');
    if (existing.replaceAll('\r\n', '\n') !== xml) {
      throw new Error('Sitemap is out of date. Run npm run generate:sitemap.');
    }
    console.log('Sitemap matches the current application configuration.');
  } else {
    await writeFile(sitemapFile, xml, 'utf8');
  }
  console.log(`${languages.length} languages × ${contentPaths.length} pages = ${languages.length * contentPaths.length} URLs; ${Buffer.byteLength(xml)} bytes.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
